def test_parameter_override_reaches_the_step(split_modules):
    """``Ta`` is linear in ``Tref``, so halving it halves the tension after a step."""
    _, mech = split_modules["caisplit"]
    mesh = _mesh()
    Ta = {}
    for Tref in (120.0, 60.0):
        u = _prescribed(mesh, 1.0)
        backend = GeneratedActivation(
            mech,
            mesh,
            _f0(mesh),
            quadrature_degree=2,
            parameters={"Tref": Tref},
        )
        assert float(backend.parameters["Tref"].value) == Tref
        backend.register(u)
        _activated(backend, mech)
        backend.dt.value = 0.5
        backend.inputs["cai"].x.array[:] = 1e-3
        backend.post_solve()
        Ta[Tref] = backend.active_tension.x.array.copy()

    assert np.all(Ta[120.0] > 0.0)
    np.testing.assert_allclose(Ta[60.0], 0.5 * Ta[120.0], rtol=1e-12)


